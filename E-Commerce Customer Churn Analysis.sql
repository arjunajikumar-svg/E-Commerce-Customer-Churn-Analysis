		ROUND(AVG(TENURE),2) AS AVG_TENURE,
		ROUND(SUM(CASHBACKAMOUNT),2) AS TOT_CASH_BACK
	FROM CUSTOMER_CHURN
		WHERE CHURNSTATUS = 'CHURNED';
		
