-- TENURE --
	UPDATE CUSTOMER_CHURN
	SET TENURE = (
		SELECT TENURE FROM (SELECT TENURE, COUNT(*)
		FROM CUSTOMER_CHURN
		WHERE TENURE IS NOT NULL
		GROUP BY TENURE 
		ORDER BY COUNT(*) DESC
		LIMIT 1) AS MODE_VALUE)
	WHERE TENURE IS NULL;

	SELECT * FROM CUSTOMER_CHURN
	WHERE TENURE IS NULL;
		
-- COUPONUSED --
	UPDATE CUSTOMER_CHURN
	SET COUPONUSED = (
	SELECT COUPONUSED FROM
		(SELECT COUPONUSED, COUNT(*) AS FREQ
		 FROM CUSTOMER_CHURN
		 WHERE COUPONUSED IS NOT NULL
		 GROUP BY COUPONUSED
		 ORDER BY FREQ DESC
		 LIMIT 1 ) AS MODE_VAL)
	WHERE COUPONUSED IS NULL;

	SELECT * FROM CUSTOMER_CHURN
	WHERE COUPONUSED IS NULL;

-- ORDERCOUNT --
	UPDATE CUSTOMER_CHURN
	SET ORDERCOUNT = (
	SELECT ORDERCOUNT FROM
		(SELECT ORDERCOUNT, COUNT(*) AS FREQ
		 FROM CUSTOMER_CHURN
		 WHERE ORDERCOUNT IS NOT NULL
		 GROUP BY ORDERCOUNT
		 ORDER BY FREQ DESC
		 LIMIT 1 ) AS MODE_VAL)
	WHERE ORDERCOUNT IS NULL;

	SELECT * FROM CUSTOMER_CHURN
	WHERE ORDERCOUNT IS NULL;

